function r=phaseD_row(rec,rid,Delta,arm,method,o,fam,mS,mV,seconds,times,ada,B,idx)
met=phaseD_measure(rec,o.g,idx,B);
r=struct('scene',string(rec.truth.scene),'snr_db',rec.truth.snr_db,'record_id',rid,...
    'seed',rec.truth.seed,'input_hash',string(phaseD_hash(rec.y,'MD5')),...
    'Delta_s',Delta,'P',fam.P,'arm',string(arm),'method',string(method),...
    'eta',met.eta,'eta_SMR',mS.eta,'eta_VIT',mV.eta,'peak_db',met.peak_db,...
    'prominence_db',met.prom_db,'width_3db_hz',met.width,'track_rmse_hz',met.rmse,...
    'max_error_hz',met.maxabs,'longest_out_0p02_s',met.longest,...
    'gain_eta_vs_SMR',met.eta-mS.eta,'gain_eta_vs_VIT',met.eta-mV.eta,...
    'harm_vs_SMR',met.eta<mS.eta-0.01,'J',o.J_best,'J_start',o.J_B2,...
    'runtime_s',seconds,'t_frontend_s',times.frontend,'t_vit_s',times.vit,...
    't_family_s',times.family,'t_smr_s',times.smr,...
    'fallback',o.fallback,'hard_fail',o.hard_fail,...
    'max_coeff',max(abs(o.u)),'max_correction_hz',max(abs(fam.r*fam.Bt(idx,:)*o.u)),...
    'budget_cap',any(o.iters(:)>=o.max_iter(:)-1e-9|o.fevals(:)>=o.max_fevals(:)-1e-9),...
    'exitflags',string(jsonencode(o.exitflags)),'iterations',string(jsonencode(o.iters)),...
    'fevals',string(jsonencode(o.fevals)),'stage_seconds',string(jsonencode(o.stage_seconds)),...
    'stage_J',string(jsonencode(o.stage_J290)),'selected',string(o.selected),...
    'expansion_rounds',ada.rounds,'triggered',ada.triggered,'initial_dwell_s',ada.initial_dwell_s,...
    'final_bounds',string(jsonencode(ada.m)));
end
